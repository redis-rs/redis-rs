    /// Returns `true` if this command is split into one command per slot of its keys when they
    /// are in different slots, and the responses of these commands are combined.
    ///
    /// These are the commands with keys that have a response policy: it says how the responses
    /// of the per-slot commands are combined. Giving a command with keys a response policy
    /// therefore makes it split across slots, and it needs a key layout that can be split.
    pub(crate) fn is_split_across_slots(self) -> bool {
        !matches!(self.key_positions(), KeyPositions::Keyless(_))
            && self.response_policy().is_some()
    }

